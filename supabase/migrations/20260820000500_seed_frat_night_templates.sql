## Connection

Last week we talked about accepting responsibility and maturity. That naturally raises another question.

Who is giving us our responsibilities in the first place?

The oldest temptation in the world is the temptation to become our own master. We want to decide for ourselves what is good, what is worth sacrificing for, and where our lives ought to go.

Christianity begins somewhere very different. Before we are husbands, fathers, leaders, or mentors, we are sons.

Consider Jesus. Again and again He points to His Father. He receives His mission from the Father, entrusts Himself to the Father's will, and even teaches us to begin our own prayer with two simple words: "Our Father."

When I forget that God is my Father, I begin living like an orphan. If I do serve God, I do it like a slave not a son. Every burden feels as though it rests entirely on my shoulders and every failure threatens my identity. If we dig, most of us really don't know who we are, because we haven't let the One who can actually tell us speak to us.

But sons don't live that way. A son knows he is loved before he has accomplished anything. He receives before he achieves. He trusts before he understands. And that trust is what gives him courage.


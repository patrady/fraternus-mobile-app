## Clip Review

In this scene, Edmund, Lucy, and Eustace are unexpectedly called back to Narnia. None of them planned the journey. None of them asked for it. They simply find themselves invited into another adventure.

What becomes obvious almost immediately is that they don't all receive the invitation the same way. Edmund and Lucy step into this strange new world with wonder. Eustace spends every second complaining. He criticizes the ship, questions the crew, mocks their customs, and starts making demands.

If you know the story, the difference in reaction is because Edmund and Lucy have been matured through past experience. Eustace doesn't see he lacks the virtue that comes with maturity.

## Connection

There is something of Eustace in every one of us.

When we're young, we imagine maturity means finally getting to live life on our own terms. We've been shuttled around and protected our whole life, but when we're "adults" we can do what we want. We look forward to the day when no one can tell us what to do, and we think freedom means being able to do what we want.

Then real life begins.

A difficult task lands in your lap, your family needs more from you than you expected, a child is born, a friend asks for help at the worst possible time, your parish needs volunteers, your parents begin growing older… The list goes on.

Little by little you discover that becoming a man is not escaping responsibility, but becoming the type that knows how to carry it. Virtue is not a restriction on you as a man. It is the truth of who you are grown up and trained into authentic manhood. To do that is to ask for responsibility, to be capable of carrying it, not running away from it.

That's a key difference between a boy and a man. A boy asks, "Why should I have to?" A man begins asking, "What is God asking of me here?"

Looking back over my own life, I can see that the moments when I grew the most were rarely the moments I chose for myself. Instead, they were the moments that interrupted my plans. At the time, they felt inconvenient, but years later, I realized they were invitations. For Eustace, the adventure was an invitation to real life.

God has a remarkable way of disguising growth as responsibility.


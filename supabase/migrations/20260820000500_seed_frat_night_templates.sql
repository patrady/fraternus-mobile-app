## Connection

Curtin was telling the truth the whole time. He wasn't after Dobbs's gold at all; he was trying to keep his partner from getting a poisonous bite. But greed had overcome Dobbs, and he couldn't tell the difference between a man trying to rob him and a man trying to protect him. But notice that the treasure was in the same hole as the lizard. What he was protecting and what could poison him were under the same rock.

Greed doesn't just make a man want more; it makes him alone even when he is among his fellow men.

Generosity is open-handedness, with your money, yes, but also with your time, your attention, your strength, the credit you could keep for yourself. It starts with seeing that whatever you have was handed to you first, and that it's meant to move through you instead of piling up behind you.


## Clip Review

In this scene from 12 Angry Men, eleven jurors are convinced a boy is guilty of murder. One man isn't, and he stands alone. During a vote, it's clear that someone has changed his mind. The room turns tense fast, with one juror demanding to know who switched. Finally, the oldest man admits it was him. What I like about his explanation is that he doesn't pretend to know something he doesn't. He isn't even convinced the boy is innocent. He simply thinks the man who stood alone made a good enough case that they ought to slow down and listen a bit more.

## Connection

Can you see the humility in this scene? We sometimes mistake humility for thinking poorly of ourselves, but humility has much more to do with seeing things as they really are. Sometimes that means recognizing you're good at something. Sometimes it means recognizing you don't know something. And sometimes it means admitting you might be wrong.

I've noticed in my own life that the hardest moment in an argument isn't when I think I'm right, but when I begin to suspect I'm wrong. That's when pride kicks in. I've caught myself arguing even after I knew the other person was right or had a point. At that point, I'm not defending the truth anymore; I'm defending myself.

Like a lot of men, I don't want to lose. I don't want to look foolish. I don't want to say, "You're right. I was wrong." That is part of what makes pride such a dangerous vice for a man. It can make us more interested in feeling right than in getting things right. A proud man becomes harder to teach, harder to correct, and eventually harder to lead. He can even start mistaking stubbornness for strength.

The old man in that jury room shows us something different. He changes his mind and his actions because he cares more about finding the truth than merely protecting his original position.

As you work through The Daily Sword&Spade this week, pay attention to the moments when someone challenges or corrects you. Notice that little instinct to explain yourself right away, or to come back with, "Yeah, but..." That's often where the fight against pride begins.

## Commission

Humility ultimately leads us back to our identity in Christ. We don't have to fear admitting we're wrong, because our worth doesn't depend on always being right. God already knows the truth about us, including the parts we'd rather defend or hide, and He still calls us His sons and gives us the grace to change. So this week, don't be afraid to be corrected. Don't be afraid to change your mind. Don't be afraid to say, "I was wrong." Pride needs to feel right, but humility wants to be made right.$w27$

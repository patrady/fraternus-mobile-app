## Clip Review

In this scene from Disney's The Hunchback of Notre Dame, Frollo, a powerful judge who believes he is the most upright man in the city, has become obsessed with a woman named Esmeralda. He has just come through a long, tormented night, wrestling with a desire that is eating him alive. When his men bring word that she has slipped past them and escaped, he erupts. He swears he will find her no matter the cost, even if he has to burn down all of Paris to do it. Then, when morning comes, and one of his guards asks if he is all right, Frollo waves it off. It was nothing, he says. Just a little trouble with the fireplace.

## Connection

Consider what Frollo's desire does to him, because it tells you exactly what lust is. He would burn a whole city to the ground to get one woman. Sit with that for a moment. He does not love Esmeralda. If he loved her, he would want what is good for her. Instead, he wants to possess her, and if he cannot possess her, he would rather see her destroyed and everyone else with her.

There is one of the key differences between love and lust. Love wants the good of the other person, whereas lust wants the other person as a thing, for itself, and it will burn the world down to get it. It takes someone made in the image of God, with a soul, a story, and a whole life, and shrinks them into an object to be used. Lust stops seeing a who and starts seeing a what.

The song in this film is called "Hellfire," because that is what this desire has become in him. But remember, desire itself is not the enemy. Desire is a fire, and fire can be good. A fire in the hearth warms the whole house. But a fire that breaks loose burns the house to the ground. Frollo's fire is loose, and it is devouring him from the inside.

The most dangerous part is that Frollo thinks he is pure. He has spent his whole life certain he is cleaner and holier than everyone around him. So when the fire finally shows itself in him, he cannot admit it. He will not confess it. "A little trouble with the fireplace." That is a lie, and it is the exact lie lust loves best. Lust does its worst work in the dark, in secret, behind the mask of a man who has it all handled.

The man in real danger is not the one who says, "I am fighting this, and it is hard." That man is in the fight. The man in danger is the one like Frollo, who pretends there is no fire at all while it quietly burns him up.

We need to understand what chastity is, because it is not what Frollo had and it is not what most people think. It is not being cold, or a prude, or afraid of women, or ashamed of your own body. Chastity is the strength to look at a person and see a person, and to love them as one. It is desire that has been trained and rightly aimed, so that you see a soul where lust would see a thing. Far from being weak, it is one of the strongest things a man can carry, because it means your fire answers to you.

This is one of the hardest and most constant fights you will ever face as men, and the enemy loves it, because he gets to attack you twice. He attacks with the desire itself, and then he attacks with the shame that comes after, because shame drives a man into the dark, and isolation is exactly where lust grows strongest.

So this week, as you work through The Daily Sword&Spade, fight lust in the light and don't go it alone. When the temptations come, name them honestly instead of pretending, like Frollo, that there is no problem. Like a fire needs fuel, the one thing lust needs most is secrecy.

## Commission

